async def seed_cities():
    async with async_session_maker() as session:
        # Check if cities already exist
        result = await session.execute(select(City).limit(1))
        if result.scalar_one_or_none():
            print("Cities already seeded. Use --force to reseed.")
            if "--force" not in sys.argv:
                return
            # Clear existing
            await session.execute(text("DELETE FROM cities"))
            print("Cleared existing cities.")

        cities = []
        for name, oblast, lat, lng, pop, is_rc in UKRAINIAN_CITIES:
            cities.append(City(
                name=name,
                oblast=oblast,
                country="UA",
                latitude=lat,
                longitude=lng,
                population=pop,
                is_regional_center=is_rc,
            ))

        session.add_all(cities)
        await session.commit()
        print(f"Seeded {len(cities)} Ukrainian cities.")


if __name__ == "__main__":
    asyncio.run(seed_cities())
